const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const errs = [];
  const mk = async (n) => { const c = await b.newContext({ viewport: { width: 1100, height: 900 } }); await c.addInitScript(() => { window.__CARREAU_EMULATOR = true; }); const p = await c.newPage(); p.on('pageerror', e => errs.push(n + ': ' + e.message)); return p; };
  const w = ms => new Promise(r => setTimeout(r, ms)); const log = (...a) => console.log(...a);
  const newComp = async (p, name, teams) => { await p.click('[data-act="new-t"]'); await w(2500);
    await p.evaluate(async ([name, teams]) => { const S = window.__carreau.S; const t = JSON.parse(JSON.stringify(S.tournaments[S.tid])); t.name = name;
      for (let i = 0; i < teams; i++) t.teams.push({ id: 'e' + i, name: 'Team ' + i, players: ['a'], active: true }); await S.store.setTournament(t); }, [name, teams]); await w(800); };
  const A = await mk('A'); await A.goto(process.env.WEB_URL); await w(3500);
  await newComp(A, 'Adm A1 empty', 0); await newComp(A, 'Adm A2 full', 6);
  const B = await mk('B'); await B.goto(process.env.WEB_URL); await w(3500);
  await newComp(B, 'Adm B1', 4);
  const AD = await mk('admin'); await AD.goto(process.env.WEB_URL + '#admin'); await w(3000);
  await AD.evaluate(() => window.__testGoogle('samuelcblakey@gmail.com')); await w(4000);
  const txt = async (sel) => (await AD.textContent(sel)).replace(/\s+/g, ' ');
  const cr = await txt('#adm-creators');
  log('creators panel has visitors:', /Visitor \d/.test(cr), '| device recorded:', /Chrome/.test(cr));
  const menu = await AD.evaluate(async () => { document.querySelector('[data-act="admin-exit"]').click(); await new Promise(r => setTimeout(r, 300)); document.querySelector('.picker-btn').click(); await new Promise(r => setTimeout(r, 200));
    const txt = [...document.querySelectorAll('.pick-row')].map(o => o.textContent).join('|'); document.querySelector('.picker-btn').click(); location.hash = 'admin'; await new Promise(r => setTimeout(r, 600)); return txt; });
  log('admin menu hides visitor comps:', !/Adm A1|Adm A2|Adm B1/.test(menu));
  const row = await AD.evaluate(() => { const r = [...document.querySelectorAll('#adm-comps .erow')].find(x => x.textContent.includes('Adm A2 full')); return r ? r.textContent.replace(/\s+/g, ' ') : ''; });
  log('row shows creator, teams, status:', /Visitor \d/.test(row) && /6 teams/.test(row) && /Registration/.test(row));
  await AD.click('[data-act="adm-filter"][data-k="empty"]'); await w(300);
  const empty = await txt('#adm-comps'); log('empty filter:', empty.includes('Adm A1 empty') && !empty.includes('Adm A2 full'));
  await AD.click('[data-act="adm-filter"][data-k="all"]'); await w(200);
  await AD.fill('#adm-q', 'Adm B'); await w(300);
  const srch = await AD.evaluate(() => [...document.querySelectorAll('#adm-comps .erow')].filter(r => r.offsetParent !== null).map(r => r.textContent).join('|'));
  log('search:', srch.includes('Adm B1') && !srch.includes('Adm A1'));
  await AD.fill('#adm-q', ''); await w(200);
  // nickname the creator of A's comps
  const aUid = await A.evaluate(() => window.__carreau.S.tournaments[window.__carreau.S.tid].ownerUid);
  await AD.click(`[data-act="adm-name"][data-uid="${aUid}"]`); await w(200);
  await AD.fill('#adm-name', 'Club A'); await AD.click(`[data-act="adm-name-save"][data-uid="${aUid}"]`); await w(1500);
  log('nickname shown:', (await txt('#adm-creators')).includes('Club A'));
  log('visitor cannot read nicknames:', await B.evaluate(async () => { try { const r = await fetch('http://127.0.0.1:8080/v1/projects/demo-carreau/databases/(default)/documents/config/creators'); return r.status; } catch (e) { return 'err'; } }) !== 200);
  // show theirs + bulk delete
  await AD.click(`[data-act="adm-creator"][data-uid="${aUid}"]`); await w(300);
  const theirs = await txt('#adm-comps'); log('show theirs:', theirs.includes('Adm A1') && theirs.includes('Adm A2') && !theirs.includes('Adm B1'));
  await AD.click('[data-act="adm-sel-all"]'); await w(200);
  await AD.click('[data-act="adm-bulk-del"]'); await w(200);
  log('confirm shown:', (await txt('#adm-comps')).includes('Delete 2 competitions'));
  await AD.click('[data-act="adm-bulk-del-yes"]'); await w(4000);
  log('bulk delete toast:', await AD.textContent('#toast'));
  const left = await AD.evaluate(() => Object.values(window.__carreau.S.tournaments).map(t => t.name).join('|'));
  log('A comps gone, B kept:', !/Adm A/.test(left) && /Adm B1/.test(left));
  await A.reload(); await w(3500);
  log('A list after delete:', await A.evaluate(() => Object.values(window.__carreau.S.tournaments).filter(t => /Adm A/.test(t.name)).length));
  await AD.click(`[data-act="adm-creator"][data-uid="${aUid}"]`).catch(() => {}); await w(300); await AD.screenshot({ path: process.env.OUT + '/admin.png', fullPage: true });
  log('errs', errs); await b.close();
})();
